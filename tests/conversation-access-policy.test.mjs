import assert from "node:assert/strict";
import {authorizeConversationAccess,validateFinalConversationMessage} from "../cloudflare/src/conversation-access-policy.js";
const actor={authenticated:true,active:true,userId:"u1",tenantId:"tenantA"};
const conversation={id:"thread1",tenantId:"tenantA",status:"active"};
const membership={active:true,userId:"u1",tenantId:"tenantA",conversationId:"thread1",role:"member"};
const allow=(operation,change={})=>authorizeConversationAccess({actor,conversation,membership,operation,...change}).allowed;
for(const op of ["read","append"])assert.equal(allow(op),true);
assert.equal(allow("delete"),false);
assert.equal(allow("read",{actor:{...actor,tenantId:"tenantB"}}),false);
assert.equal(allow("append",{conversation:{...conversation,tenantId:"tenantB"}}),false);
assert.equal(allow("read",{membership:{...membership,conversationId:"thread2"}}),false);
assert.equal(allow("read",{actor:{...actor,authenticated:false}}),false);
assert.equal(allow("read",{membership:{...membership,active:false}}),false);
assert.equal(allow("read",{conversation:{...conversation,status:"deleted"}}),false);
assert.equal(allow("append",{membership:{...membership,role:"viewer"}}),false);
assert.equal(allow("delete",{membership:{...membership,role:"admin"}}),true);
assert.equal(allow("read",{actor:{...actor,userId:"other"}}),false);
assert.equal(allow("read",{membership:{...membership,role:"superuser"}}),false);
assert.equal(validateFinalConversationMessage({role:"user",sourceKind:"voice_final",content:"Hello",idempotencyKey:"turn_1"}).valid,true);
assert.equal(validateFinalConversationMessage({role:"user",sourceKind:"voice_partial",content:"Hello",idempotencyKey:"turn_1"}).valid,false);
assert.equal(validateFinalConversationMessage({role:"assistant",sourceKind:"typed",content:"Hello",idempotencyKey:"turn_1"}).valid,false);
assert.equal(validateFinalConversationMessage({role:"user",sourceKind:"typed",content:"",idempotencyKey:"turn_1"}).valid,false);
console.log("Conversation tenant authorization kernel: 16 checks PASS");
