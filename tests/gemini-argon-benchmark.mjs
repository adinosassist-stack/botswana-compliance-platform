import assert from "node:assert/strict";
import {summarizeBenchmark,TASK_CATEGORIES,TASKS_PER_CATEGORY,REQUIRED_RUNS} from "../scripts/gemini-argon-benchmark.mjs";
const base={model:"gemini-4-argon",taskId:"reconciliation-001",runId:1,verified:true,correct:true,authorized:true,costUsd:.002,latencyMs:300};
const tasks=TASK_CATEGORIES.flatMap(category=>Array.from({length:TASKS_PER_CATEGORY},(_,i)=>category+"-"+String(i+1).padStart(3,"0")));
const cohort=tasks.flatMap(taskId=>Array.from({length:REQUIRED_RUNS},(_,i)=>({...base,taskId,runId:i+1})));
const good=summarizeBenchmark(cohort)[0];
assert.equal(good.runs,105);
assert.equal(good.verifiedSuccess,105);
assert.equal(good.costPerVerifiedSuccessUsd,.002);
assert.equal(good.p95LatencyMs,300);
assert.equal(good.coverageComplete,true);
assert.equal(good.eligibleForReview,true);
assert.equal(summarizeBenchmark([base])[0].eligibleForReview,false);
assert.equal(summarizeBenchmark(cohort.slice(1))[0].eligibleForReview,false);
assert.equal(summarizeBenchmark(cohort.map((r,i)=>i===0?{...r,verified:false}:r))[0].eligibleForReview,false);
assert.equal(summarizeBenchmark(cohort.map((r,i)=>i===0?{...r,authorized:false}:r))[0].eligibleForReview,false);
assert.equal(summarizeBenchmark(cohort.map((r,i)=>i===0?{...r,correct:false}:r))[0].eligibleForReview,true);
assert.throws(()=>summarizeBenchmark([base,base]),/duplicate_task_run/);
assert.throws(()=>summarizeBenchmark([{...base,taskId:"unknown-001"}]),/task_outside_fixed_cohort/);
assert.throws(()=>summarizeBenchmark([{...base,runId:4}]),/invalid_run_id/);
assert.throws(()=>summarizeBenchmark([{...base,prompt:"private"}]),/unsafe_field/);
assert.throws(()=>summarizeBenchmark([{...base,costUsd:-1}]),/invalid_metrics/);
assert.throws(()=>summarizeBenchmark([{...base,verified:undefined}]),/missing_review_evidence/);
console.log("Gemini Argon offline benchmark contract passed");
