import assert from "node:assert/strict";
import {encodeConversationCursor,decodeConversationCursor} from "../cloudflare/src/conversation-cursor-rehearsal.js";
import {readFromTrustedSession} from "../cloudflare/src/conversation-session-boundary-rehearsal.js";
const secret="0123456789abcdef0123456789abcdef";
const context={session:{authenticated:true,active:true,userId:"u1",tenantId:"tenantA"},workspaceMembership:{active:true,userId:"u1",tenantId:"tenantA",conversationId:"chat1",role:"member"},conversation:{id:"chat1",tenantId:"tenantA",status:"active"}};
const cursor=await encodeConversationCursor({tenantId:"tenantA",threadId:"chat1",createdAt:"2026-10-30 12:00:00",messageId:"msg1",secret});
const parsed=await decodeConversationCursor({cursor,tenantId:"tenantA",threadId:"chat1",secret});
assert.equal(parsed.messageId,"msg1");
let reads=0;
const env={DB:{prepare(){return{bind(){return{async all(){reads++;return{results:[]}}}}}}}};
assert.equal((await readFromTrustedSession({env,context})).ok,true);
assert.equal(reads,1);
const revoked={...context,workspaceMembership:{...context.workspaceMembership,active:false}};
assert.equal((await readFromTrustedSession({env,context:revoked})).error,"access_denied");
assert.equal(reads,1,"revoked member must not query second page");
const switched={...context,session:{...context.session,tenantId:"tenantB"}};
assert.equal((await readFromTrustedSession({env,context:switched})).error,"access_denied");
assert.equal(await decodeConversationCursor({cursor,tenantId:"tenantB",threadId:"chat1",secret}),null);
assert.equal(await decodeConversationCursor({cursor,tenantId:"tenantA",threadId:"other-chat",secret}),null);
assert.equal(reads,1);
console.log("Multi-page conversation reauthorization and cross-tenant cursor rejection PASS");
