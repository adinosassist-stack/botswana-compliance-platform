import assert from "node:assert/strict";
import {sanitizeAgentRun,evaluateAgentRuns} from "../cloudflare/src/agent-reliability-advisor.js";
const base={tenantId:"tenant-A",actorTenantId:"tenant-A",traceId:"run-1",workflow:"reconciliation",outcome:"success",authorization:"allow",costMinor:10,inputTokens:20,outputTokens:5};
const sanitized=sanitizeAgentRun({...base,prompt:"secret",apiKey:"sk-private",toolArguments:{account:"123"}});
assert.equal(sanitized.prompt,undefined);
assert.equal(sanitized.apiKey,undefined);
assert.equal(sanitized.toolArguments,undefined);
assert.equal(sanitizeAgentRun({...base,actorTenantId:"tenant-B"}),null);
assert.equal(sanitizeAgentRun({...base,traceId:"../../unsafe"}),null);
assert.equal(sanitizeAgentRun({...base,costMinor:-1}).costMinor,null);
const result=evaluateAgentRuns([base,{...base,traceId:"run-2",outcome:"denied",authorization:"deny",costMinor:null},{...base,tenantId:"tenant-B",actorTenantId:"tenant-B",traceId:"other"}],"tenant-A");
assert.equal(result.total,2);
assert.equal(result.counts.denied,1);
assert.equal(result.knownCostMinor,10);
assert.equal(result.missingCost,1);
assert.equal(result.status,"unverified");
assert.ok(result.recommendations.length>0);
assert.equal(evaluateAgentRuns([base],"tenant-B").total,0);
console.log("agent reliability advisor tests passed");
