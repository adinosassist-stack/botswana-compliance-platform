import assert from "node:assert/strict";
import {createConversationStagingRoute} from "../cloudflare/src/conversation-staging-route-rehearsal.js";
let resolved=0;
const worker=createConversationStagingRoute(async()=>{resolved++;return null});
const env={APP_ENV:"staging",DEPLOYMENT_ENV:"staging",DEPLOYMENT_PROFILE:"conversation-staging",CONVERSATION_HISTORY_STAGING_ENABLED:"true",CONVERSATION_STAGING_ORIGIN:"https://conversation-staging.example.invalid"};
const url="https://conversation-staging.example.invalid/api/conversation-staging/threads/thread1/messages";
const request=(u=url,method="GET")=>new Request(u,{method});
assert.equal((await worker.fetch(request(),{...env,DEPLOYMENT_ENV:"production"})).status,404);
assert.equal((await worker.fetch(request(),{...env,CONVERSATION_HISTORY_STAGING_ENABLED:"false"})).status,404);
assert.equal((await worker.fetch(request("https://other.example.invalid/api/conversation-staging/threads/thread1/messages"),env)).status,403);
assert.equal((await worker.fetch(request(url,"PUT"),env)).status,405);
assert.equal((await worker.fetch(request(),env)).status,401);
assert.equal(resolved,1,"only gated authorized route should invoke server resolver");
console.log("Dedicated conversation staging route remains gated PASS");
