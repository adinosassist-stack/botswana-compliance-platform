import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url)), root=path.resolve(here,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('public/index.html'),worker=read('cloudflare/src/worker.js'),server=read('server/server.js'),wrangler=read('cloudflare/wrangler.toml'),sw=read('public/sw.js');
const manifest=JSON.parse(read('public/manifest.webmanifest')),pkg=JSON.parse(read('package.json'));
const slugs=['cipa-compliance-botswana','burs-tax-compliance-botswana','business-licences-botswana','employment-compliance-botswana','tender-readiness-botswana','compliance-evidence-botswana','pricing'];
const ok=[]; const check=(n,v)=>{assert.ok(v,n);ok.push(n)};
check('release 1.21.20',pkg.version.startsWith('1.21.')&&Number(pkg.version.split('.')[2]||0)>=20);
check('PWA cache 1.21.20',sw.includes(`bw-business-protection-v78-${pkg.version}`));
check('homepage language en-BW',html.includes('<html lang="en-BW">'));
check('Google eligible PNG favicon linked',html.includes('rel="icon" type="image/png" sizes="96x96" href="/assets/favicon-96.png"')&&fs.existsSync(path.join(root,'public/assets/favicon-96.png')));
check('PWA icons present',manifest.icons?.some(x=>x.sizes==='192x192')&&manifest.icons?.some(x=>x.sizes==='512x512'));
check('organization schema uses brand logo not hero',html.includes('"logo":"__SEO_LOGO__"')&&!html.includes('"logo":"__SEO_OG_IMAGE__"'));
check('homepage links all SEO guides',slugs.every(slug=>html.includes(`href="/${slug}/"`)));
check('guide routes declared in Worker',slugs.every(slug=>worker.includes(`"${slug}"`))&&worker.includes('seoGuideResponse'));
check('guide routes worker-first in Wrangler',slugs.every(slug=>wrangler.includes(`"/${slug}/*"`)));
check('Cloudflare trailing slash canonicalization explicit',wrangler.includes('html_handling = \"auto-trailing-slash\"'));
check('Node guide rendering parity',server.includes('renderSeoGuide(req,slug)')&&server.includes('SEO_GUIDE_SLUGS'));
check('sitemap expands to guide slugs',worker.includes('...SEO_GUIDE_SLUGS.map')&&server.includes('...SEO_GUIDE_SLUGS.map'));
check('sitemap omits ignored priority/changefreq hints',!worker.includes('<changefreq>')&&!worker.includes('<priority>'));
const titles=new Set(),descs=new Set(),h1s=new Set();
for(const slug of slugs){
  const file=path.join(root,'public',slug,'index.html'); check(`${slug} file exists`,fs.existsSync(file));
  const s=fs.readFileSync(file,'utf8');
  const title=(s.match(/<title>([^<]+)<\/title>/)||[])[1]||'', desc=(s.match(/<meta name="description" content="([^"]+)"/)||[])[1]||'', h1=(s.match(/<h1>([^<]+)<\/h1>/)||[])[1]||'';
  titles.add(title);descs.add(desc);h1s.add(h1);
  const text=s.replace(/<style>[\s\S]*?<\/style>/g,' ').replace(/<script[\s\S]*?<\/script>/g,' ').replace(/<[^>]+>/g,' ').replace(/\s+/g,' ').trim();
  const words=text.split(' ').filter(Boolean);
  check(`${slug} substantial useful content`,words.length>=380);
  check(`${slug} dynamic canonical`,s.includes('rel="canonical" href="__SEO_PAGE_URL__"'));
  check(`${slug} Botswana locale`,s.includes('<html lang="en-BW">')&&s.includes('og:locale" content="en_BW"'));
  check(`${slug} structured WebPage + breadcrumb`,s.includes('"@type":"WebPage"')&&s.includes('"@type":"BreadcrumbList"'));
  check(`${slug} brand favicon`,s.includes('/assets/favicon-96.png'));
  check(`${slug} brand logo schema`,s.includes('"logo":"__SEO_LOGO__"'));
  check(`${slug} lightweight no app JavaScript`,(s.match(/<script/g)||[]).length===1&&s.includes('type="application/ld+json"'));
  check(`${slug} no deprecated FAQPage markup`,!s.includes('"FAQPage"'));
  check(`${slug} internal cross-links`,slugs.filter(x=>x!==slug).some(x=>s.includes(`href="/${x}/"`)));
  check(`${slug} no query-string CTA crawl duplicate`,!s.includes('href="/?')&&!s.includes("href='/?"));
}
check('guide titles unique',titles.size===slugs.length);
check('guide descriptions unique',descs.size===slugs.length);
check('guide H1s unique',h1s.size===slugs.length);
const pricing=read('public/pricing/index.html');
check('pricing page lists all five public plan names and prices',['Monitor','Protect','Control','Network','Partner','P149','P349','P699','P1,299','P2,499'].every(x=>pricing.includes(x)));
check('BURS guide preserves fail-closed positioning',read('public/burs-tax-compliance-botswana/index.html').includes('Annual turnover is not treated as a substitute for taxable supplies'));
check('official-source links present where useful',read('public/cipa-compliance-botswana/index.html').includes('https://www.cipa.co.bw/')&&read('public/burs-tax-compliance-botswana/index.html').includes('https://www.burs.org.bw/')&&read('public/business-licences-botswana/index.html').includes('https://trade.gov.bw/'));
console.log(`v78 1.21.20 SEO expansion adversarial: ${ok.length}/${ok.length} PASS`);
