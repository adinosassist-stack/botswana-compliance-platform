import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
const pkg=JSON.parse(fs.readFileSync(new URL('../package.json',import.meta.url),'utf8'));
const sw=fs.readFileSync(new URL('../public/sw.js',import.meta.url),'utf8');
const checks=[];
const ok=(name,cond)=>{assert.ok(cond,name);checks.push(name)};
ok('package bumped for registration clarity',pkg.version.startsWith('1.21.')&&Number(pkg.version.split('.')[2]||0)>=20);
ok('top navigation says Create account',html.includes('data-bw-onclick="startFreeFromMarketing()">Start free</button>'));
ok('hero has direct Create free account CTA',html.includes('data-bw-onclick="startFreeFromMarketing()">Start free for 14 days</button>'));
ok('pricing CTAs identify the trial',html.match(/>Start free<\/button>/g)?.length>=5);
ok('registration still opens register mode directly',html.includes("function openAuthFromMarketing(mode=\"register\")")&&html.includes('setAuthMode(mode)'));
ok('auth card has a visible mode-specific title',html.includes('id="authTitle"')&&html.includes('Create your business account'));
ok('register mode shows a registration-specific explanation',html.includes('Quick start asks only a few business facts before your first protection check.'));
ok('trial note explicitly says no card is required to register',html.includes('No payment card is required to register.'));
ok('trial note is hidden on sign in',html.includes('trialNote.hidden=!registering'));
ok('company name remains register-only',html.includes('companyNameField.style.display=registering?"block":"none"'));
ok('register primary action is explicit',html.includes('Create account & workspace'));
ok('sign-in primary action remains Sign in',html.includes('?"Create account & workspace":"Sign in"'));
ok('register social Google wording is explicit',html.includes('Create account with Google'));
ok('register social Facebook wording is explicit',html.includes('Create account with Facebook'));
ok('sign-in social wording remains available',html.includes('?"Create account with Google":"Continue with Google"'));
ok('auth tabs retain both Sign in and Create account',html.includes('id="loginTab"')&&html.includes('>Sign in</button>')&&html.includes('id="registerTab"')&&html.includes('>Create account</button>'));
ok('back control clearly returns to website',html.includes('← Back to website'));
ok('registration keeps company plan selection',html.includes('payload.companyName=authCompany.value.trim()')&&html.includes('payload.plan=safeSessionGet("bwcos_selected_plan")'));
ok('service worker cache bumped',sw.includes(`bw-business-protection-v78-${pkg.version}`));
console.log(`v78 registration clarity: ${checks.length}/${checks.length} checks passed`);
