import crypto from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
let pass=0,fail=0;const ok=(v,m)=>{if(v){console.log('PASS',m);pass++}else{console.error('FAIL',m);fail++}};
const raw=crypto.randomBytes(32).toString('base64url');
ok(raw.length===43&&/^[A-Za-z0-9_-]{43}$/.test(raw),'issued Node reset token matches bounded 256-bit base64url format');
const db=new DatabaseSync(':memory:');
db.exec(`
create table users(id text primary key,password_hash text,password_salt text,session_generation integer not null default 0,password_reset_version integer not null default 0);
create table sessions(id text primary key,user_id text,revoked_at text);
create table password_reset_tokens(id text primary key,user_id text,token_hash text unique,expires_at text,used_at text,created_at text default current_timestamp);
insert into users values('u1','old-hash','old-salt',0,0);
insert into sessions values('s1','u1',null);
insert into sessions values('s2','u1',null);
insert into password_reset_tokens(id,user_id,token_hash,expires_at) values('r1','u1','h1',datetime('now','+30 minutes'));
insert into password_reset_tokens(id,user_id,token_hash,expires_at) values('r2','u1','h2',datetime('now','+30 minutes'));
insert into password_reset_tokens(id,user_id,token_hash,expires_at,used_at) values('failed','u1','hf',datetime('now','+30 minutes'),current_timestamp);
insert into password_reset_tokens(id,user_id,token_hash,expires_at) values('expired','u1','he',datetime('now','-1 minute'));
`);
const eligible=db.prepare("select user_id from password_reset_tokens where token_hash=? and used_at is null and expires_at>current_timestamp limit 1");
ok(eligible.get('h1')?.user_id==='u1','live reset token is cheaply eligible before password work');
ok(!eligible.get('hf'),'failed-delivery token cannot be used');
ok(!eligible.get('he'),'expired reset token cannot be used');
const claim=db.prepare("update password_reset_tokens set used_at=current_timestamp where token_hash=? and user_id=? and used_at is null and expires_at>current_timestamp returning user_id");
ok(claim.get('h1','u1')?.user_id==='u1','first reset token can be claimed exactly once');
db.prepare("update users set password_hash=?,password_salt=?,session_generation=session_generation+1,password_reset_version=password_reset_version+1 where id=?").run('new-hash','new-salt','u1');
db.prepare("update sessions set revoked_at=current_timestamp where user_id=? and revoked_at is null").run('u1');
db.prepare("update password_reset_tokens set used_at=current_timestamp where user_id=? and used_at is null").run('u1');
ok(!claim.get('h1','u1'),'same reset token replay loses final claim');
ok(!claim.get('h2','u1'),'second concurrently issued token is invalid after serialized first reset succeeds');
const u=db.prepare("select session_generation,password_reset_version,password_hash from users where id='u1'").get();
ok(u.session_generation===1&&u.password_reset_version===1&&u.password_hash==='new-hash','successful reset advances generations and stores new credential');
ok(db.prepare("select count(*) n from sessions where user_id='u1' and revoked_at is null").get().n===0,'successful reset revokes all existing sessions');
ok(db.prepare("select count(*) n from password_reset_tokens where user_id='u1' and used_at is null").get().n===0,'successful reset leaves no reusable reset token');
console.log(`V78 1.21.71 Node password reset parity runtime: ${pass}/${pass+fail} PASS`);if(fail)process.exit(1);
