import assert from "node:assert/strict";
import {readConversationPageRehearsal} from "../cloudflare/src/conversation-page-reader-rehearsal.js";
const actor={authenticated:true,active:true,userId:"user1",tenantId:"tenantA"};
const conversation={id:"thread1",tenantId:"tenantA",status:"active"};
const membership={active:true,userId:"user1",tenantId:"tenantA",conversationId:"thread1",role:"member"};
const secret="0123456789abcdef0123456789abcdef";
const base={actor,conversation,membership,secret};
let calls=0;
const failing={DB:{prepare(){calls++;return {bind(){return {async all(){throw Error("private Cloudflare token in error")}}}}}}};
assert.deepEqual(await readConversationPageRehearsal({...base,env:failing}),{ok:false,error:"storage_unavailable"});
assert.equal(calls,1);
const broken={DB:{prepare(){return {bind(){return {async all(){return {success:false,results:[]}}}}}}}};
assert.deepEqual(await readConversationPageRehearsal({...base,env:broken}),{ok:false,error:"storage_unavailable"});
assert.deepEqual(await readConversationPageRehearsal({...base,env:{}}),{ok:false,error:"schema_unavailable"});
assert.deepEqual(await readConversationPageRehearsal({...base,env:failing,membership:{...membership,active:false}}),{ok:false,error:"access_denied"});
assert.equal(calls,1,"unauthorized request must not touch database");
const empty={DB:{prepare(){return {bind(...args){assert.deepEqual(args,["tenantA","thread1",51]);return {async all(){return {success:true,results:[]}}}}}}}};
const page=await readConversationPageRehearsal({...base,env:empty,limit:1000});
assert.deepEqual(page,{ok:true,items:[],nextCursor:null});
console.log("Conversation reader failure isolation and bounded queries PASS");
