#!/usr/bin/env node
// Issue #2578: uncredentialed, READ-ONLY Cloudflare Access boundary qualification.
// No login, cookies, tokens, D1 writes, deploys, or customer data.
const REQUIRED_PATHS=[
 '/auth/',
 '/manager-invite/owner/',
 '/manager-invite/activate/',
 '/manager-invite/dashboard/',
 '/api/auth/me',
 '/api/workspace/managers/directory',
 '/api/workspace/managers/my-dashboard'
];

export function normalizeStagingTarget(origin,accessDomain){
 const site=new URL(origin);
 if(site.protocol!=='https:'||site.username||site.password||site.search||site.hash||site.pathname!=='/'||
    !/^[a-z0-9.-]+$/i.test(site.hostname)||!site.hostname.includes('.')||
    /(?:^|\.)(?:localhost|example\.com|example\.invalid)$/.test(site.hostname))
  throw new Error('invalid_staging_https_origin');
 const host=String(accessDomain||'').toLowerCase().trim();
 if(!/^[a-z0-9-]+\.cloudflareaccess\.com$/.test(host))throw new Error('invalid_cloudflare_access_team_domain');
 return {origin:site.origin,accessDomain:host};
}

export function assertAccessBoundary({status,location,accessDomain,body}){
 // 401/403 may be generated by a bare application endpoint, not Access.
 // A 404-only inert Worker also cannot prove an Access policy.
 if(status!==302&&status!==303)throw new Error('access_redirect_required');
 if(typeof location!=='string'||!location)throw new Error('access_redirect_missing');
 const target=new URL(location);
 if(target.protocol!=='https:'||target.hostname.toLowerCase()!==accessDomain||
    !/^\/cdn-cgi\/access\/(login|authorize)(?:\/|\?|$)/.test(target.pathname+target.search))
  throw new Error('unexpected_access_redirect_destination');
 if(typeof body==='string'&&/(?:csrfToken|sessionCookie|tokenHash|passwordHash)/i.test(body))
  throw new Error('credential_material_present');
 return true;
}

export async function qualifyPrivateAccess({origin,accessDomain,fetchFn=fetch}){
 const target=normalizeStagingTarget(origin,accessDomain),results=[];
 for(const path of REQUIRED_PATHS){
  const url=target.origin+path;
  const r=await fetchFn(url,{method:'GET',redirect:'manual',credentials:'omit',
   headers:{accept:'text/html,application/json;q=0.9','cache-control':'no-store'}});
  assertAccessBoundary({status:r.status,location:r.headers.get('location'),accessDomain:target.accessDomain});
  results.push({path,accessDenied:true,status:r.status});
 }
 return {ok:true,origin:target.origin,checked:results};
}

const calledAsCli=process.argv[1]&&import.meta.url===new URL('file://'+process.argv[1]).href;
if(calledAsCli){
 try{
  const origin=process.env.MANAGER_STAGING_ORIGIN,accessDomain=process.env.MANAGER_STAGING_ACCESS_TEAM_DOMAIN;
  if(!origin||!accessDomain)throw new Error('staging_origin_and_access_team_domain_required');
  const result=await qualifyPrivateAccess({origin,accessDomain});
  process.stdout.write(JSON.stringify(result,null,2)+'\n');
 }catch(e){process.stderr.write('MANAGER_ACCESS_PREFLIGHT_FAILED: '+e.message+'\n');process.exitCode=1;}
}
